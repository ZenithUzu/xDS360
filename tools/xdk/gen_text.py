# Builds xdk/frontend/xds_text_data.cpp:
# - the Spanish menu text, from xdk/lang/es.txt;
# - the letters NooDS's font lacks (á é í ó ú ñ ü ¿ ¡ and capitals), made from
#   its own letters so they match: base letter + accent, tilde from '~',
#   dots from the dot of 'i', ¿ and ¡ as '?' and '!' turned upside down.
# Needs Pillow and the NooDS sources (scripts/fetch_noods.sh).
# Strings are written with octal escapes, so VS2010 reads them byte for byte.
import os
import re
from PIL import Image, ImageChops, ImageDraw

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
FONT = os.path.join(ROOT, 'third_party', 'noods', 'src', 'ui', 'console', 'images', 'font.bmp')
LANG = os.path.join(ROOT, 'xdk', 'lang', 'es.txt')
OUT = os.path.join(ROOT, 'xdk', 'frontend', 'xds_text_data.cpp')
UI = os.path.join(ROOT, 'xdk', 'noods', 'ui', 'console', 'console_ui.cpp')

font = Image.open(FONT).convert('RGBA')


def cell(ch):
    k = ord(ch) - 32
    return font.crop((48 * (k % 10), 48 * (k // 10), 48 * (k % 10) + 48, 48 * (k // 10) + 48)).getchannel('A')


def width_of(ch):
    text = open(UI).read()
    widths = [int(v) for v in re.findall(r'\d+', re.search(r'charWidths\[\] = \{(.*?)\};', text, re.S).group(1))]
    return widths[ord(ch) - 32]


def lighter(a, b):
    return ImageChops.lighter(a, b)


def with_acute(ch, top):
    base = cell(ch)
    if ch == 'i':  # dotless i: drop the dot first
        base = base.crop((0, 15, 48, 48))
        empty = Image.new('L', (48, 48), 0)
        empty.paste(base, (0, 15))
        base = empty
    box = base.getbbox()
    cx = (box[0] + box[2]) / 2
    big = Image.new('L', (192, 192), 0)
    ImageDraw.Draw(big).line([((cx - 2) * 4, (top + 5) * 4), ((cx + 2.5) * 4, top * 4)], fill=255, width=11)
    return lighter(base, big.resize((48, 48), Image.LANCZOS))


def with_mark(ch, mark, top):
    """Paste a mark (tilde or dots) centred over the letter, its top at `top`."""
    base = cell(ch)
    box, mbox = base.getbbox(), mark.getbbox()
    mark = mark.crop(mbox)
    layer = Image.new('L', (48, 48), 0)
    layer.paste(mark, (int(round((box[0] + box[2] - mark.width) / 2)), top))
    return lighter(base, layer)


def dots():
    dot = cell('i').crop((0, 0, 48, 15))
    dot = dot.crop(dot.getbbox())
    two = Image.new('L', (dot.width * 2 + 5, dot.height), 0)
    two.paste(dot, (0, 0))
    two.paste(dot, (dot.width + 5, 0))
    out = Image.new('L', (48, 48), 0)
    out.paste(two, (0, 0))
    return out


def upside_down(ch):
    """'?' or '!' turned over, its top just above the lowercase height."""
    g = cell(ch).rotate(180)
    g = g.crop(g.getbbox())
    box = cell(ch).getbbox()
    out = Image.new('L', (48, 48), 0)
    out.paste(g, (box[0], 17))
    return out


tilde = Image.new('L', (48, 48), 0)
tilde.paste(cell('~'), (0, 0))
LOW, CAP = 9, 3  # where marks start over lowercase and capital letters
EXTRAS = [
    ('á', with_acute('a', LOW), 'a'), ('é', with_acute('e', LOW), 'e'), ('í', with_acute('i', LOW), 'i'),
    ('ó', with_acute('o', LOW), 'o'), ('ú', with_acute('u', LOW), 'u'),
    ('Á', with_acute('A', CAP), 'A'), ('É', with_acute('E', CAP), 'E'), ('Í', with_acute('I', CAP), 'I'),
    ('Ó', with_acute('O', CAP), 'O'), ('Ú', with_acute('U', CAP), 'U'),
    ('ñ', with_mark('n', tilde, LOW), 'n'), ('Ñ', with_mark('N', tilde, CAP), 'N'),
    ('ü', with_mark('u', dots(), LOW + 1), 'u'), ('Ü', with_mark('U', dots(), CAP + 1), 'U'),
    ('¿', upside_down('?'), '?'), ('¡', upside_down('!'), '!'),
]


def c_string(text):
    out = ''
    for b in text.encode('utf-8'):
        if b == 0x0A:
            out += '\\n'
        elif b in (0x22, 0x5C):
            out += '\\' + chr(b)
        elif 32 <= b < 127:
            out += chr(b)
        else:
            out += '\\%03o' % b
    return '"' + out + '"'


pairs = []
for line in open(LANG, encoding='utf-8'):
    line = line.rstrip('\n')
    if not line or line.startswith('#'):
        continue
    english, spanish = line.split('\t')
    pairs.append((english.replace('\\n', '\n'), spanish.replace('\\n', '\n')))

# Every English text must be one the menu really draws, or it is never used.
LIT = r'"(?:[^"\\\n]|\\.)*"'
ui = re.sub(r'//[^\n]*', '', open(UI).read())
known = set(''.join(p[1:-1] for p in re.findall(LIT, m.group(0))).replace('\\n', '\n')
            for m in re.finditer(r'%s(?:\s*%s)*' % (LIT, LIT), ui))
missing = [e for e, _ in pairs if e not in known]
if missing:
    raise SystemExit('Not in console_ui.cpp (typo in es.txt?): %r' % missing)

out = ['// SPDX-License-Identifier: GPL-3.0-or-later',
       '// Generated by tools/xdk/gen_text.py from xdk/lang/es.txt and NooDS\'s font:',
       '// regenerate instead of editing.',
       '',
       'extern const int xdsExtraCount = %d;' % len(EXTRAS),
       '',
       '// Unicode code of each extra letter (accented vowels, n with tilde, u with dots, inverted ? and !).',
       'extern const unsigned short xdsExtraCodes[] = { %s };' % ', '.join('0x%02X' % ord(c) for c, _, _ in EXTRAS),
       'extern const unsigned char xdsExtraWidths[] = { %s };' % ', '.join(str(width_of(b)) for _, _, b in EXTRAS),
       '',
       'extern const unsigned char xdsExtraAlpha[][48 * 48] = {']
for ch, img, _ in EXTRAS:
    data = img.tobytes()
    out.append('    { // U+%04X' % ord(ch))
    out += ['        ' + ','.join('%d' % v for v in data[i:i + 32]) + ',' for i in range(0, len(data), 32)]
    out.append('    },')
out.append('};')
out.append('')
out.append('extern const char *const xdsSpanish[][2] = {')
for english, spanish in pairs:
    out.append('    { %s, %s },' % (c_string(english), c_string(spanish)))
out.append('    { 0, 0 }')
out.append('};')
with open(OUT, 'w', newline='\r\n') as f:
    f.write('\n'.join(out) + '\n')

# A picture of the new letters, for checking them by eye.
sheet = Image.new('RGB', (48 * len(EXTRAS), 48), (0, 0, 0))
for i, (_, img, _) in enumerate(EXTRAS):
    sheet.paste(Image.new('RGB', (48, 48), (255, 255, 255)), (48 * i, 0), img)
preview = os.environ.get('XDS_TEXT_PREVIEW')
if preview:
    sheet.resize((sheet.width * 2, 96), Image.NEAREST).save(preview)
print('%d letters, %d translations -> %s' % (len(EXTRAS), len(pairs), OUT))
