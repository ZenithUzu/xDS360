# Builds xdk/frontend/xbox_buttons.cpp: the menu's button icons, from Microsoft's
# XNA "Xbox 360 Controller Button Images" pack (Ms-PL):
# https://github.com/SimonDarksideJ/XNAGameStudio/wiki/Xbox-360-Controller-Button-Images
# Based on Apariencia-Emulador's herramientas/gen_button_glyphs.py.
#
# Usage: python3 tools/xdk/gen_xbox_buttons.py <the pack's ButtonImages folder> [output .cpp]
# Needs Pillow.
#
# NooDS draws these as characters of its font: each one is a 48x48 cell of
# font.bmp that main.cpp overwrites at start-up. The GPU then shrinks the cell
# to SCALE(34) with bilinear filtering and blends with plain (not
# premultiplied) alpha. So:
# - Scale in PREMULTIPLIED alpha ("RGBa"), Lanczos, then a light unsharp
#   mask: plain RGBA scaling leaves a dark rim, bilinear leaves them blurry.
# - Store NOT premultiplied (0xAARRGGBB), what the blend expects.
# - Fill the colour of fully transparent pixels from their visible
#   neighbours: the GPU's bilinear filter mixes them into the edge.
import os
import sys
from PIL import Image, ImageFilter

SRC = sys.argv[1]
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.dirname(os.path.abspath(__file__)), '..', '..', 'xdk', 'frontend', 'xbox_buttons.cpp')

# character in the font, picture in the pack, size inside the 48x48 cell
BUTTONS = [(0x80, 'ButtonA', 46, 46), (0x81, 'ButtonB', 46, 46), (0x82, 'ButtonX', 46, 46),
           (0x83, 'Start', 48, 44), (0x7F, 'Back', 48, 46)]


def cell(name, w, h):
    im = Image.open(os.path.join(SRC, 'xboxController%s.tga' % name)).convert('RGBA')
    im = im.crop(im.getchannel('A').getbbox())
    im = im.convert('RGBa').resize((w, h), Image.LANCZOS)   # premultiplied: no dark fringes
    im = im.filter(ImageFilter.UnsharpMask(radius=0.8, percent=90, threshold=0)).convert('RGBA')
    out = Image.new('RGBA', (48, 48), (0, 0, 0, 0))
    out.paste(im, ((48 - w) // 2, (48 - h) // 2))
    return bleed(out)


def bleed(im):
    """Transparent pixels take the average colour of their visible neighbours
    (a few rings out), keeping alpha 0."""
    px = im.load()
    known = set((x, y) for y in range(48) for x in range(48) if px[x, y][3])
    for _ in range(3):
        grown = {}
        for y in range(48):
            for x in range(48):
                if (x, y) in known:
                    continue
                near = [px[x + dx, y + dy] for dy in (-1, 0, 1) for dx in (-1, 0, 1)
                        if 0 <= x + dx < 48 and 0 <= y + dy < 48 and (x + dx, y + dy) in known]
                if near:
                    grown[(x, y)] = tuple(sum(p[i] for p in near) // len(near) for i in range(3)) + (0,)
        for (x, y), p in grown.items():
            px[x, y] = p
        known.update(grown)
    return im


out = ['''// Xbox 360 controller button images, from Microsoft's XNA Game Studio
// "Xbox 360 Controller Button Images" pack (Microsoft Permissive License,
// Ms-PL; see licencias/XNA-botones-MsPL.txt). Scaled in premultiplied alpha
// with Lanczos and sharpened; 0xAARRGGBB, not premultiplied, one 48x48 font
// cell each. Generated by tools/xdk/gen_xbox_buttons.py: regenerate instead of editing.

// Font characters the pictures replace: A, B, X, Start, Back.
extern const unsigned char xboxButtonChars[%d] = { %s };

extern const unsigned int xboxButtonPixels[%d][48 * 48] = {''' % (
    len(BUTTONS), ', '.join('0x%02X' % c for c, _, _, _ in BUTTONS), len(BUTTONS))]
for char, name, w, h in BUTTONS:
    data = cell(name, w, h).tobytes()
    vals = ['0x%02X%02X%02X%02X' % (data[i + 3], data[i], data[i + 1], data[i + 2])
            for i in range(0, len(data), 4)]
    out.append('    { // %s' % name)
    out += ['        ' + ','.join(vals[i:i + 12]) + ',' for i in range(0, len(vals), 12)]
    out.append('    },')
out.append('};')
with open(OUT, 'w', newline='\r\n') as f:
    f.write('\n'.join(out) + '\n')
print(OUT)
