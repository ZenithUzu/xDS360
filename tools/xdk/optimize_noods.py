"""Reproducible XDK optimizations, applied after the VS2010 conversion.

Direct calls are derived from NooDS's own decoder, not a second ARM spec.
Only homogeneous 16-entry rows are accelerated; all others keep the table.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]

def arm_rows(text):
    table = text.split('Interpreter::armInstrs[])(uint32_t) = {', 1)[1].split('};', 1)[0]
    entries = re.findall(r'&Interpreter::(\w+)', table)
    if len(entries) != 4096:
        raise ValueError('Expected exactly 4096 ARM decoder entries')
    return {row: entries[row * 16] for row in range(256)
            if len(set(entries[row * 16:row * 16 + 16])) == 1
            and entries[row * 16] != 'unkArm'}

def decoder(text):
    rows = arm_rows(text)
    groups = {}
    for row, handler in rows.items():
        groups.setdefault(handler, []).append(row)
    lines = ['// Generated by tools/xdk/optimize_noods.py from NooDS (GPL-3.0-or-later).',
             '// Included inside Interpreter::runOpcode(), after condition evaluation.',
             '// Define XDS_ARM_DIRECT=0 to compare the original member-pointer dispatch.',
             '#ifndef XDS_ARM_DIRECT', '#define XDS_ARM_DIRECT 1', '#endif',
             '#if XDS_ARM_DIRECT', 'switch ((opcode >> 20) & 0xFFu) {']
    for handler, group in groups.items():
        lines.append(' '.join('case 0x%02X:' % row for row in group))
        lines.append('    return %s(opcode);' % handler)
    lines += ['default: break;', '}', '#endif', '']
    return '\n'.join(lines)

def replace(path, old, new, count=1):
    text = path.read_text()
    if text.count(old) != count:
        raise ValueError('%s: expected %d occurrences of %r' % (path, count, old[:70]))
    path.write_text(text.replace(old, new))

def optimize(out):
    arm = out / 'core/arm'
    (arm / 'arm_direct.inc').write_text(decoder((arm / 'interpreter_lookup.cpp').read_text()))
    replace(arm / 'interpreter.cpp',
        '                // ARM branches dominate tight game loops.',
        '#include "arm_direct.inc"\n                // ARM branches dominate tight game loops.')
    # The UI edits Settings::frameskip, but the Xenon GPU reads an atomic request.
    # Publish it without changing render cadence halfway through an emulated frame.
    ui = out / 'ui/console/console_ui.cpp'
    replace(ui, '        // Check if GBA mode changed',
        '        core->gpu.requestFrameSkip(Settings::frameskip);\n\n        // Check if GBA mode changed')
    replace(out / 'core/gpu/gpu.cpp', '    if (skip > 3) skip = 3;',
        '    if (skip > 5) skip = 5; // match the six settings-menu choices')
    # Keep textures alive across display refreshes. Rebuild only when a new
    # image arrives, the format changes, or a pause may replace the Core.
    replace(ui, '    while (running) {\n        core->gpu.requestFrameSkip',
        '    void *gbaTexture = nullptr, *topTexture = nullptr, *botTexture = nullptr;\n'
        '    bool textureGba = gbaMode, textureShift = false;\n'
        '    while (running) {\n        core->gpu.requestFrameSkip')
    replace(ui, '        void *gbaTexture = nullptr, *topTexture = nullptr, *botTexture = nullptr;\n', '')
    replace(ui, '        core->gpu.getFrame(framebuffer, gbaMode);',
        '        const bool freshFrame = core->gpu.getFrame(framebuffer, gbaMode);\n'
        '        if (freshFrame || textureGba != gbaMode || textureShift != shift) {\n'
        '            if (gbaTexture) destroyTexture(gbaTexture);\n'
        '            if (topTexture) destroyTexture(topTexture);\n'
        '            if (botTexture) destroyTexture(botTexture);\n'
        '            gbaTexture = topTexture = botTexture = nullptr;\n'
        '            textureGba = gbaMode;\n'
        '            textureShift = shift;\n'
        '        }')
    for name in ('gbaTexture', 'topTexture', 'botTexture'):
        replace(ui, '            ' + name + ' = createTexture(',
            '            if (!' + name + ') ' + name + ' = createTexture(')
    old = ('        if (gbaTexture) destroyTexture(gbaTexture);\n'
           '        if (topTexture) destroyTexture(topTexture);\n'
           '        if (botTexture) destroyTexture(botTexture);')
    replace(ui, old, '')
    replace(ui, '        // Finish drawing and free textures\n        endFrame();\n\n',
        '        // Submit this refresh; retain screen textures until the next image.\n        endFrame();\n')
    cleanup = ('    if (gbaTexture) destroyTexture(gbaTexture);\n'
               '    if (topTexture) destroyTexture(topTexture);\n'
               '    if (botTexture) destroyTexture(botTexture);\n')
    replace(ui, '            // Open the pause menu\n            pauseMenu();',
        '            // A pause can replace the ROM or change the output format.\n' +
        ''.join('        ' + line + '\n' for line in cleanup.splitlines()) +
        '            gbaTexture = topTexture = botTexture = nullptr;\n'
        '            pauseMenu();')
    replace(ui, '\n}\n\nint ConsoleUI::setPath', '\n' + cleanup + '}\n\nint ConsoleUI::setPath')
    from native_video import apply_native_video
    apply_native_video(out)

if __name__ == '__main__':
    optimize(ROOT / 'xdk/noods')
